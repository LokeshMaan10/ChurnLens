"""Generate the README results section and the interview walkthrough from saved outputs.

Run with `python -m churnlens.docsgen` (or `make docs`). Every figure is read from a file the
pipeline wrote; nothing here is typed in. Rerun after any phase changes its outputs.
"""

from __future__ import annotations

import json
from typing import Any

import pandas as pd

from churnlens.config import PROJECT_ROOT, load_config, resolve_path
from churnlens.reporting import write_section
from churnlens.tools import db

README = PROJECT_ROOT / "README.md"
WALKTHROUGH = PROJECT_ROOT / "reports" / "interview_walkthrough.md"


def facts() -> dict[str, Any]:
    """Collect headline numbers from pipeline artifacts."""
    data = load_config("data")
    r = lambda p: resolve_path(p, data)  # noqa: E731
    con = db.connection().cursor()
    f: dict[str, Any] = {"mode": data["mode"],
                         "pct": 100 if data["mode"] == "full" else data["user_sample_pct"],
                         "seed": data["sample_seed"]}
    f["n_a"], f["churn_a"] = con.execute("SELECT COUNT(*), AVG(is_churn) FROM labels_a").fetchone()
    f["n_b"], f["churn_b"] = con.execute("SELECT COUNT(*), AVG(is_churn) FROM labels_b").fetchone()
    s = json.loads(r("reports/model/summary.json").read_text(encoding="utf-8"))
    f["model"] = s["selected"]
    f["threshold"] = s["threshold"]
    f["test"] = s["models"][s["selected"]]["test"]
    f["oof"] = s["models"][s["selected"]]["oof"]
    f["all_models"] = {k: v["test"]["pr_auc"] for k, v in s["models"].items()}
    f["ablation"] = s.get("ablation")
    tk = pd.read_csv(r("reports/model/top_k.csv")).set_index("top_pct")
    f["top5_recall"], f["top5_precision"] = tk.loc[5, "recall"], tk.loc[5, "precision"]
    f["confusion"] = s["confusion"]
    seg = pd.read_csv(r("reports/eda/segment_tests.csv")).head(3)
    f["top_dims"] = list(zip(seg["title"], seg["cramers_v"], strict=True))
    rates = pd.read_csv(r("reports/eda/segment_rates.csv"))
    ar = rates[rates["dimension"] == "auto_renew"].set_index("group")["rate"]
    f["churn_autorenew"], f["churn_manual"] = ar.get("auto-renew"), ar.get("manual renew")
    grp = pd.read_csv(r("reports/explain/B_group_importance.csv"), index_col=0).iloc[:, 0]
    f["shap_groups"] = list((grp / grp.sum()).head(3).items())
    cox = pd.read_csv(r("reports/value/cox_summary.csv"), index_col=0)
    f["hr_autorenew"] = cox.loc["auto_renew", "exp(coef)"]
    f["hr_free"] = cox.loc["free_start", "exp(coef)"]
    bt = pd.read_csv(r("reports/value/backtest.csv"))
    bt = bt[bt["scope"] == "renewers, 30-day plans"].set_index("method")
    f["backtest"] = bt[["total_ratio", "mae"]].to_dict(orient="index")
    f["cltv_choice"] = r("reports/value/cltv_choice.txt").read_text(encoding="utf-8").strip()
    pol = pd.read_csv(r("reports/prioritize/B_policies.csv")).set_index("policy")
    f["policies"] = pol["expected_net_benefit"].to_dict()
    f["policy_churn_rates"] = pol["churn_rate_contacted"].to_dict()
    quad = pd.read_csv(r("reports/prioritize/B_quadrants.csv")).set_index("quadrant")
    f["high_risk_evar_share"] = float(quad.loc[[q for q in quad.index if q.startswith("high")],
                                               "total_evar"].sum() / quad["total_evar"].sum())
    drift = json.loads(r("reports/monitoring/drift_summary.json").read_text(encoding="utf-8"))
    f["pred_psi"] = drift["prediction"]["psi"]
    f["retrain"] = drift["retrain"]
    f["drift_top"] = drift["features"][0]
    ge = pd.read_csv(r("reports/agent_eval/golden_results.csv"))
    an = ge[~ge["id"].str.startswith(("brief", "plan", "drift"))]
    f["eval"] = {"n": len(an), "numeric": an["numeric_ok"].mean(), "sql": an["sql_ok"].mean(),
                 "grounded": (ge["ungrounded"] == "[]").mean()}
    sf = pd.read_csv(r("reports/agent_eval/safety_results.csv"))
    f["safety"] = (int(sf["passed"].sum()), len(sf))
    live = r("data/processed/{mode}/scoring/C_scores.parquet")
    if live.exists():
        c = pd.read_parquet(live)
        f["live"] = (len(c), float(c["p_churn"].mean()))
    return f


def readme_results(f: dict[str, Any]) -> str:
    t = f["test"]
    lines = [
        f"_Generated by `python -m churnlens.docsgen` from pipeline outputs. Data: {f['mode']} "
        f"mode, {f['pct']}% user sample (seed {f['seed']}). Full detail: "
        "[`reports/results.md`](reports/results.md)._", "",
        "| Result | Value |", "|---|---|",
        f"| Users (train A / test B) | {f['n_a']:,} / {f['n_b']:,} |",
        f"| Churn rate (A / B) | {f['churn_a']:.2%} / {f['churn_b']:.2%} |",
        f"| Selected model | {f['model']} (chosen on A only) |",
        f"| PR-AUC / ROC-AUC on out-of-time B | {t['pr_auc']:.3f} / {t['roc_auc']:.3f} |",
        f"| Churners caught in the riskiest 5% of B | {f['top5_recall']:.1%} "
        f"(precision {f['top5_precision']:.1%}) |",
        f"| CLTV method (lower backtest error) | {f['cltv_choice']} |",
        f"| Optimizer expected net benefit (placeholder costs) | "
        f"{f['policies']['optimizer (benefit − λ × cost)']:,.0f} NTD |",
        f"| Prediction drift A → B (PSI) / retrain verdict | {f['pred_psi']:.3f} / "
        f"{'retrain' if f['retrain']['retrain'] else 'no retrain'} |",
        f"| Agent golden set (offline mode): numeric / SQL / grounded | "
        f"{f['eval']['numeric']:.0%} / {f['eval']['sql']:.0%} / {f['eval']['grounded']:.0%} "
        f"({f['eval']['n']} analyst questions) |",
        f"| Agent safety tests passed | {f['safety'][0]}/{f['safety'][1]} |",
    ]
    return "\n".join(lines)


def walkthrough(f: dict[str, Any]) -> str:
    t, c = f["test"], f["confusion"]
    dims = "; ".join(f"{d} (Cramér's V {v:.2f})" for d, v in f["top_dims"])
    groups = ", ".join(f"{g} {s:.0%}" for g, s in f["shap_groups"])
    bt = f["backtest"]
    ab = f["ablation"]
    reasons = "; ".join(f["retrain"]["reasons"]) or "none"
    live = (f"- Live scoring of April 2017 expirations (no labels yet): {f['live'][0]:,} users, "
            f"mean predicted churn {f['live'][1]:.2%}.\n") if "live" in f else ""
    return f"""# Interview walkthrough: ChurnLens

_Generated by `python -m churnlens.docsgen` from the pipeline's saved outputs; every number
below is read from those files. Data: KKBox churn challenge, {f['mode']} mode, {f['pct']}% user
sample (seed {f['seed']})._

## 1. What the data showed

- Training snapshot A has {f['n_a']:,} users whose membership expired in February 2017;
  {f['churn_a']:.2%} churned. The out-of-time test snapshot B (March) has {f['n_b']:,} users
  and {f['churn_b']:.2%} churn.
- The strongest single associations with churn were payment-side: {dims}. Users on auto-renew
  churned at {f['churn_autorenew']:.1%} vs {f['churn_manual']:.1%} on manual renewal.
- Listening behaviour separated churn far more weakly than payment behaviour, in the
  segment tables and in RFM segmentation.
- In a Cox model of subscription spells, auto-renew had a hazard ratio of
  {f['hr_autorenew']:.2f} and a free first payment {f['hr_free']:.2f} (associations; the
  proportional-hazards assumption is violated for several covariates, so these are
  time-averaged).
- Data issues found and handled: a later transaction export rewrote old expiry dates
  (excluded to avoid label leakage); a feature that counts days since the first observed
  transaction tracks the calendar because history starts in January 2015.

## 2. What the model predicts

- {f['model']} predicts the probability that a customer churns at their next expiry, using
  only data from before the snapshot cutoff. On the out-of-time month: PR-AUC {t['pr_auc']:.3f}
  against a {t['base_rate']:.1%} base rate, ROC-AUC {t['roc_auc']:.3f}, Brier {t['brier']:.4f}.
- Contacting the riskiest 5% of customers reaches {f['top5_recall']:.1%} of churners at
  {f['top5_precision']:.1%} precision. At the cost-based threshold ({f['threshold']:.3f}),
  precision is {c['precision']:.1%} and recall {c['recall']:.1%}.
- What the model relies on (SHAP), by feature group: {groups}.
- Gender, age and city are excluded; adding them changed out-of-time PR-AUC by
  {ab['test_with'] - ab['test_without']:+.4f}.

## 3. How to use it for the business

- Rank customers by expected value at risk (P(churn) × CLTV): high-risk customers hold
  {f['high_risk_evar_share']:.0%} of it. CLTV uses the {f['cltv_choice']} method, which backtested
  within {abs(bt[f['cltv_choice']]['total_ratio'] - 1):.1%} of realized two-month revenue.
- A rules engine maps each customer's top driver to an action; an optimizer picks whom to
  contact under a budget and a contact cap: expected net benefit
  {f['policies']['optimizer (benefit − λ × cost)']:,.0f} NTD vs
  {f['policies']['highest P(churn) first']:,.0f} NTD for a plain "highest risk first" list
  (placeholder costs and save rates).
- Agents answer questions and draft briefs and campaign plans using read-only tools; in the
  offline evaluation every number in every answer traced back to a tool output.
{live}
## 4. What it does not prove

- Nothing here shows cause and effect. SHAP values, segment differences and hazard ratios
  describe associations in observational data and what the model relies on.
- Whether an action reduces churn is unknown until the designed randomized test (with a
  holdout) is run; the A/B and uplift results in the report are SIMULATED.
- Money figures depend on placeholder costs, save rates and margin.
- Calibrated probabilities ran low on the test month; the retraining policy fired
  ({reasons}). Prediction drift itself was small (PSI {f['pred_psi']:.3f}).
- Results come from a {f['pct']}% user sample; the full-data run is `mode: full` in
  `configs/data.yaml`.
"""


def main() -> int:
    f = facts()
    write_section(README, "readme_results", readme_results(f))
    WALKTHROUGH.write_text(walkthrough(f), encoding="utf-8")
    print(f"docs: README results + {WALKTHROUGH.relative_to(PROJECT_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
