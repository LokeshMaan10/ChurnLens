"""Phase 0 data audit: profile every raw table and flag oddities.

Run with `python -m churnlens.analysis.audit` (or `make audit`). All queries
run in DuckDB over Parquet. Writes:
  - reports/audit/profile.json      (machine-readable profile)
  - the `audit` section of reports/results.md
  - docs/data_dictionary.md         (column docs from docs/columns.yaml + profile stats)
Nothing is cleaned here; cleaning rules are Phase 1.
"""

from __future__ import annotations

import itertools
import json
from dataclasses import asdict, dataclass
from typing import Any

import duckdb
import yaml

from churnlens.config import PROJECT_ROOT, date_to_int, load_config, resolve_path
from churnlens.data.views import register_raw_views
from churnlens.reporting import fmt_int, fmt_pct, md_table, run_banner, write_section

DICTIONARY_HEADER = ("# Data dictionary\n\n_Generated by code (raw tables: Phase 0 audit; "
                     "features: Phase 5). Do not edit by hand._\n")
LOG_COUNT_COLUMNS = ["num_25", "num_50", "num_75", "num_985", "num_100"]
TXN_NUMERIC_COLUMNS = ["payment_method_id", "payment_plan_days", "plan_list_price",
                       "actual_amount_paid", "is_auto_renew", "is_cancel"]


@dataclass
class Check:
    """One oddity check: rows of `table` matching `where` are counted."""

    table: str
    name: str
    where: str
    description: str
    severity: str = "flag"  # flag = likely data problem; info = worth knowing, not an error


@dataclass
class CheckResult:
    """Outcome of a Check (or a cross-table check)."""

    table: str
    name: str
    count: int
    denominator: int
    severity: str
    description: str


# ---------------------------------------------------------------- profiling


def invalid_date_sql(col: str) -> str:
    """SQL predicate: a non-null YYYYMMDD integer that is not a real calendar date."""
    return f"({col} IS NOT NULL AND try_strptime(CAST({col} AS VARCHAR), '%Y%m%d') IS NULL)"


def profile_table(con: duckdb.DuckDBPyConnection, table: str, keys: list[str],
                  date_columns: list[str]) -> dict[str, Any]:
    """Row count, per-column nulls/distinct/min/max, duplicates, unique msno, date ranges."""
    columns = con.execute(f"DESCRIBE {table}").fetchall()
    rows = con.execute(f"SELECT COUNT(*) FROM {table}").fetchone()[0]
    col_profiles = []
    for col_name, col_type, *_ in columns:
        q = (f"SELECT COUNT(*) - COUNT({col_name}), COUNT(DISTINCT {col_name}), "
             f"MIN({col_name}), MAX({col_name})")
        if col_type == "VARCHAR":
            q += f", COUNT(*) FILTER (WHERE {col_name} = '')"
        stats = con.execute(f"{q} FROM {table}").fetchone()
        col_profiles.append({
            "name": col_name, "type": col_type, "nulls": stats[0], "distinct": stats[1],
            # msno min/max are meaningless hashes; keep the profile readable.
            "min": None if col_name == "msno" else stats[2],
            "max": None if col_name == "msno" else stats[3],
            "empty_strings": stats[4] if col_type == "VARCHAR" else None,
        })
    full_dups = con.execute(
        f"SELECT COALESCE(SUM(c - 1), 0) FROM (SELECT *, COUNT(*) AS c FROM {table} "
        f"GROUP BY ALL HAVING COUNT(*) > 1)").fetchone()[0]
    key_dups = None
    if keys:
        k = ", ".join(keys)
        key_dups = con.execute(
            f"SELECT COUNT(*) - (SELECT COUNT(*) FROM (SELECT DISTINCT {k} FROM {table})) "
            f"FROM {table}").fetchone()[0]
    unique_msno = con.execute(f"SELECT COUNT(DISTINCT msno) FROM {table}").fetchone()[0]
    date_ranges = {
        c: list(con.execute(f"SELECT MIN({c}), MAX({c}) FROM {table}").fetchone())
        for c in date_columns
    }
    return {"table": table, "rows": rows, "columns": col_profiles, "full_row_duplicates":
            int(full_dups), "key_columns": keys, "key_duplicates": key_dups,
            "unique_msno": unique_msno, "date_ranges": date_ranges}


# ---------------------------------------------------------------- checks


def build_checks(tables: list[str], audit_cfg: dict[str, Any],
                 cutoffs: dict[str, int]) -> list[Check]:
    """Per-table oddity checks, parameterised from configs/audit.yaml and snapshot cutoffs."""
    age = audit_cfg["plausible_age"]
    min_date = date_to_int(audit_cfg["min_plausible_date"])
    max_secs = audit_cfg["max_seconds_per_day"]
    checks: list[Check] = []
    for t in tables:
        if t in ("train", "train_v2"):
            checks.append(Check(t, "label_not_binary", "is_churn NOT IN (0, 1) OR is_churn IS NULL",
                                "is_churn is not 0/1"))
        elif t == "members_v3":
            checks += [
                Check(t, "bd_zero_or_negative", "bd <= 0", "age (bd) is 0 or negative"),
                Check(t, "bd_below_min", f"bd > 0 AND bd < {age['min']}",
                      f"age between 1 and {age['min'] - 1}"),
                Check(t, "bd_above_max", f"bd > {age['max']}", f"age above {age['max']}"),
                Check(t, "gender_missing", "gender IS NULL OR gender = ''", "gender missing",
                      "info"),
                Check(t, "registration_invalid_date", invalid_date_sql("registration_init_time"),
                      "registration_init_time is not a valid date"),
            ] + [
                Check(t, f"registered_on_or_after_cutoff_{s}",
                      f"registration_init_time >= {c}",
                      f"registered on/after snapshot {s} cutoff ({c})", "info")
                for s, c in cutoffs.items()
            ]
        elif t.startswith("transactions"):
            negatives = " OR ".join(f"{c} < 0" for c in TXN_NUMERIC_COLUMNS)
            checks += [
                Check(t, "list_price_zero", "plan_list_price = 0", "plan_list_price is 0"),
                Check(t, "paid_zero", "actual_amount_paid = 0", "actual_amount_paid is 0", "info"),
                Check(t, "paid_zero_list_positive",
                      "actual_amount_paid = 0 AND plan_list_price > 0",
                      "paid 0 although list price > 0", "info"),
                Check(t, "paid_above_list", "actual_amount_paid > plan_list_price",
                      "paid more than list price"),
                Check(t, "plan_days_zero", "payment_plan_days = 0", "payment_plan_days is 0"),
                Check(t, "negative_values", negatives, "any numeric field negative"),
                Check(t, "expire_before_transaction",
                      "membership_expire_date < transaction_date",
                      "membership expires before the transaction date"),
                Check(t, "expire_implausible_date", f"membership_expire_date < {min_date}",
                      f"membership_expire_date before {min_date} (e.g. 1970-01-01)"),
                Check(t, "invalid_dates", f"{invalid_date_sql('transaction_date')} OR "
                      f"{invalid_date_sql('membership_expire_date')}", "unparseable date"),
                Check(t, "is_cancel", "is_cancel = 1", "cancellation transactions", "info"),
            ] + [
                Check(t, f"transaction_on_or_after_cutoff_{s}", f"transaction_date >= {c}",
                      f"transaction on/after snapshot {s} cutoff ({c}); excluded from its features",
                      "info")
                for s, c in cutoffs.items()
            ]
        elif t.startswith("user_logs"):
            plays = " + ".join(LOG_COUNT_COLUMNS)
            neg_counts = " OR ".join(f"{c} < 0" for c in [*LOG_COUNT_COLUMNS, "num_unq"])
            checks += [
                Check(t, "total_secs_negative", "total_secs < 0", "total_secs negative"),
                Check(t, "total_secs_above_day", f"total_secs > {max_secs}",
                      f"total_secs above {max_secs:,} (more than a day)"),
                Check(t, "negative_counts", neg_counts, "a play count is negative"),
                Check(t, "unique_exceeds_plays", f"num_unq > {plays}",
                      "more unique songs than total plays"),
                Check(t, "zero_activity", f"({plays}) = 0 AND total_secs = 0",
                      "row with no plays and no seconds", "info"),
                Check(t, "invalid_dates", invalid_date_sql("date"), "unparseable date"),
            ]
    return checks


def run_checks(con: duckdb.DuckDBPyConnection, checks: list[Check],
               row_counts: dict[str, int]) -> list[CheckResult]:
    """Count matching rows for each check."""
    results = []
    for c in checks:
        n = con.execute(f"SELECT COUNT(*) FROM {c.table} WHERE {c.where}").fetchone()[0]
        results.append(CheckResult(c.table, c.name, n, row_counts[c.table], c.severity,
                                   c.description))
    return results


def cross_table_checks(con: duckdb.DuckDBPyConnection, tables: list[str],
                       row_counts: dict[str, int], cutoffs: dict[str, int]) -> list[CheckResult]:
    """Checks spanning two tables: v1/v2 overlap and label coverage."""
    out: list[CheckResult] = []

    def scalar(sql: str) -> int:
        return int(con.execute(sql).fetchone()[0])

    if {"transactions", "transactions_v2"} <= set(tables):
        out.append(CheckResult(
            "transactions_v2", "identical_rows_in_v1", scalar(
                "SELECT COUNT(*) FROM (SELECT * FROM transactions_v2 "
                "INTERSECT SELECT * FROM transactions)"),
            row_counts["transactions_v2"], "flag",
            "distinct rows present identically in both transaction files (dedupe in Phase 1)"))
        out.append(CheckResult(
            "transactions_v2", "same_msno_date_rows_differ", scalar(
                "SELECT COUNT(*) FROM (SELECT msno, transaction_date FROM transactions_v2 "
                "INTERSECT SELECT msno, transaction_date FROM transactions) k WHERE NOT EXISTS ("
                "SELECT 1 FROM transactions_v2 a "
                "JOIN transactions b USING (msno, transaction_date) "
                "WHERE a.msno = k.msno AND a.transaction_date = k.transaction_date "
                "AND a.membership_expire_date = b.membership_expire_date "
                "AND a.actual_amount_paid = b.actual_amount_paid AND a.is_cancel = b.is_cancel "
                "AND a.payment_plan_days = b.payment_plan_days)"),
            row_counts["transactions_v2"], "flag",
            "(msno, transaction_date) pairs in both files where no row matches on expiry, amount, "
            "plan days and cancel flag: v2 can restate a transaction with later values"))
        b_cut = cutoffs.get("B")
        if b_cut:
            out.append(CheckResult(
                "transactions_v2", "rows_before_cutoff_B",
                scalar(f"SELECT COUNT(*) FROM transactions_v2 WHERE transaction_date < {b_cut}"),
                row_counts["transactions_v2"], "info",
                f"v2 rows dated before {b_cut}, i.e. inside the period v1 already covers"))
    if {"user_logs", "user_logs_v2"} <= set(tables):
        out.append(CheckResult(
            "user_logs_v2", "msno_date_in_v1", scalar(
                "SELECT COUNT(*) FROM (SELECT msno, date FROM user_logs_v2 "
                "INTERSECT SELECT msno, date FROM user_logs)"),
            row_counts["user_logs_v2"], "flag", "(msno, date) keys also present in user_logs"))
    if {"train", "train_v2"} <= set(tables):
        out.append(CheckResult(
            "train_v2", "users_also_in_train",
            scalar("SELECT COUNT(*) FROM (SELECT msno FROM train_v2 "
                   "INTERSECT SELECT msno FROM train)"),
            row_counts["train_v2"], "info", "label users present in both label files"))
    for label in ("train", "train_v2"):
        if label not in tables:
            continue
        for other, what in (("members_v3", "members_v3"),
                            ("transactions", "transactions (v1)"), ("user_logs", "user_logs (v1)")):
            if other in tables:
                n = scalar(f"SELECT COUNT(*) FROM {label} l WHERE NOT EXISTS "
                           f"(SELECT 1 FROM {other} o WHERE o.msno = l.msno)")
                out.append(CheckResult(label, f"users_missing_from_{other}", n,
                                       row_counts[label], "info",
                                       f"label users with no row in {what}"))
    return out


def overlap_matrix(con: duckdb.DuckDBPyConnection, tables: list[str]) -> dict[str, dict[str, int]]:
    """Pairwise count of distinct msno shared between tables (diagonal = table's own count)."""
    matrix: dict[str, dict[str, int]] = {t: {} for t in tables}
    for t in tables:
        matrix[t][t] = con.execute(f"SELECT COUNT(DISTINCT msno) FROM {t}").fetchone()[0]
    for a, b in itertools.combinations(tables, 2):
        n = con.execute(f"SELECT COUNT(*) FROM (SELECT msno FROM {a} INTERSECT "
                        f"SELECT msno FROM {b})").fetchone()[0]
        matrix[a][b] = matrix[b][a] = n
    return matrix


# ---------------------------------------------------------------- rendering


def render_audit_section(data_cfg: dict[str, Any], profiles: dict[str, dict[str, Any]],
                         results: list[CheckResult], matrix: dict[str, dict[str, int]]) -> str:
    """Markdown for the audit section of results.md."""
    parts = ["## Phase 0: data audit", "", run_banner(data_cfg), "",
             "Raw layer only. Nothing below has been cleaned; flags feed Phase 1 cleaning rules.",
             "", "### Table profiles", ""]
    rows = []
    for t, p in profiles.items():
        ranges = "; ".join(f"{c}: {lo}–{hi}" for c, (lo, hi) in p["date_ranges"].items()) or "—"
        key = f"{fmt_int(p['key_duplicates'])} on ({', '.join(p['key_columns'])})" \
            if p["key_columns"] else "—"
        rows.append([t, fmt_int(p["rows"]), len(p["columns"]), fmt_int(p["unique_msno"]),
                     fmt_int(p["full_row_duplicates"]), key, ranges])
    parts.append(md_table(["Table", "Rows", "Cols", "Unique msno", "Full-row dup rows",
                           "Key dup rows", "Date range(s)"], rows, "lrrrrll"))

    parts += ["", "### Null values (columns with any nulls or empty strings)", ""]
    null_rows = [[t, c["name"], fmt_int(c["nulls"]), fmt_int(c["empty_strings"] or 0),
                  fmt_pct(c["nulls"] + (c["empty_strings"] or 0), p["rows"])]
                 for t, p in profiles.items() for c in p["columns"]
                 if c["nulls"] or c["empty_strings"]]
    parts.append(md_table(["Table", "Column", "Nulls", "Empty strings", "% of rows"], null_rows,
                          "llrrr") if null_rows else "No nulls or empty strings in any column.")

    parts += ["", "### Oddity checks", "",
              "`flag` = likely data problem; "
              "`info` = expected or structural, recorded for context.", ""]
    parts.append(md_table(
        ["Table", "Check", "Rows", "% of table", "Severity", "Meaning"],
        [[r.table, f"`{r.name}`", fmt_int(r.count), fmt_pct(r.count, r.denominator, 3),
          r.severity, r.description] for r in results], "llrrll"))

    raised = [r for r in results if r.severity == "flag" and r.count > 0]
    parts += ["", "### Flags raised", ""]
    parts += [f"- **{r.table}.{r.name}**: {fmt_int(r.count)} rows "
              f"({fmt_pct(r.count, r.denominator, 3)}): {r.description}" for r in raised] \
        or ["- None."]

    tables = list(matrix)
    parts += ["", "### User overlap between tables (distinct msno in common)", ""]
    parts.append(md_table(["", *tables],
                          [[a, *(fmt_int(matrix[a][b]) for b in tables)] for a in tables],
                          "l" + "r" * len(tables)))
    return "\n".join(parts)


def render_data_dictionary(data_cfg: dict[str, Any], profiles: dict[str, dict[str, Any]],
                           column_docs: dict[str, Any]) -> str:
    """docs/data_dictionary.md: hand-written descriptions + generated statistics."""
    parts = ["## Raw tables", "",
             "_Descriptions come from `docs/columns.yaml`; statistics are generated by "
             "`python -m churnlens.analysis.audit`._", "",
             run_banner(data_cfg), "",
             "Dates are stored as KKBox's `YYYYMMDD` integers in the raw layer.", ""]
    for t, p in profiles.items():
        doc = column_docs.get(t, {})
        parts += [f"### `{t}`", "", doc.get("description", "").strip(), "",
                  f"- Grain: {doc.get('grain', '—')}",
                  f"- Rows (this sample): {fmt_int(p['rows'])}; unique msno: "
                  f"{fmt_int(p['unique_msno'])}", ""]
        rows = []
        for c in p["columns"]:
            cdoc = doc.get("columns", {}).get(c["name"], {})
            rows.append([f"`{c['name']}`", c["type"], cdoc.get("meaning", "—"),
                         fmt_int(c["nulls"]), fmt_int(c["distinct"]),
                         "—" if c["min"] is None else c["min"],
                         "—" if c["max"] is None else c["max"], cdoc.get("notes", "")])
        parts.append(md_table(["Column", "Type", "Meaning", "Nulls", "Distinct", "Min", "Max",
                               "Notes"], rows, "lllrrrrl"))
        parts.append("")
    return "\n".join(parts)


# ---------------------------------------------------------------- entry point


def main() -> int:
    """Profile, check, and write all Phase 0 outputs."""
    data_cfg = load_config("data")
    audit_cfg = load_config("audit")
    cutoffs = {s: date_to_int(v["cutoff"])
               for s, v in load_config("snapshots")["snapshots"].items()}
    con = duckdb.connect()
    tables = register_raw_views(con, data_cfg)

    profiles = {
        t: profile_table(con, t, audit_cfg["key_columns"].get(t, []),
                         data_cfg["tables"][t].get("date_columns", []))
        for t in tables
    }
    row_counts = {t: p["rows"] for t, p in profiles.items()}
    results = run_checks(con, build_checks(tables, audit_cfg, cutoffs), row_counts)
    results += cross_table_checks(con, tables, row_counts, cutoffs)
    matrix = overlap_matrix(con, tables)

    outputs = audit_cfg["outputs"]
    profile_path = resolve_path(outputs["profile_json"], data_cfg)
    profile_path.parent.mkdir(parents=True, exist_ok=True)
    profile_path.write_text(json.dumps(
        {"profiles": profiles, "checks": [asdict(r) for r in results], "overlap": matrix},
        indent=2, default=str), encoding="utf-8")
    write_section(resolve_path(outputs["results_md"], data_cfg), "audit",
                  render_audit_section(data_cfg, profiles, results, matrix))
    column_docs = yaml.safe_load(
        resolve_path(outputs["column_docs_yaml"], data_cfg).read_text(encoding="utf-8"))
    dictionary = resolve_path(outputs["data_dictionary_md"], data_cfg)
    write_section(dictionary, "raw", render_data_dictionary(data_cfg, profiles, column_docs),
                  header=DICTIONARY_HEADER)
    print(f"audit written for {len(tables)} tables -> "
          f"{profile_path.relative_to(PROJECT_ROOT)}, results.md, data_dictionary.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
